"""Shared by the single-feature tests (#154): the expected Metric of each lag feature computed here from the data, and a small generated Workload.

The expected Metrics never come from `hypotrail`: they are read from the data file and the Study's memberships with the `csv` module,
so a test that compares them with what `assess` records can disagree with it.
"""

import csv
import datetime
import hashlib
import json
import math
from pathlib import Path

from _study_helpers import EXAMPLES, run_json

BIKE_DAY = EXAMPLES / "bike_day" / "data" / "day.csv"
FIELD = "single_feature_check"
GENERATED = "gen_day"
GENERATED_FEATURES = [
    {"name": "lag_1", "kind": "lag", "period": 1},
    {"name": "lag_7", "kind": "lag", "period": 7},
    {"name": "mean_previous_7", "kind": "mean_previous", "period": 7},
]


def _rows(path) -> list:
    with Path(path).open(newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def series_of(data_file, date_column="dteday", target_column="cnt") -> dict:
    return {datetime.date.fromisoformat(r[date_column]): float(r[target_column]) for r in _rows(data_file)}


def forecast(values: dict, day: datetime.date, feature: dict) -> float:
    """The value of one lag feature for `day`, written out from its definition: `lag` is the value `period` days before, `mean_previous` the mean of the `period` days before."""
    if feature["kind"] == "lag":
        return values[day - datetime.timedelta(days=feature["period"])]
    return sum(values[day - datetime.timedelta(days=k)] for k in range(1, feature["period"] + 1)) / feature["period"]


def item_dates(study, partition, row_ids=None) -> dict:
    """{row_id: date} of the Items of `partition` in the Study's memberships, in row_id order (all of them, or those of `row_ids`)."""
    rows = _rows(Path(study) / "artifacts" / "memberships.csv")
    return {
        r["row_id"]: datetime.date.fromisoformat(r["date"])
        for r in sorted(rows, key=lambda r: r["row_id"])
        if r["partition"] == partition and (row_ids is None or r["row_id"] in row_ids)
    }


def expected_maes(study, partition, features, *, data_file=BIKE_DAY, date_column="dteday", target_column="cnt", row_ids=None) -> dict:
    """{feature name: the mean absolute error of the feature used alone as the forecast} over the Items of `partition` (or of `row_ids`)."""
    values = series_of(data_file, date_column, target_column)
    days = list(item_dates(study, partition, row_ids).values())
    return {f["name"]: math.fsum(abs(forecast(values, d, f) - values[d]) for d in days) / len(days) for f in features}


def recorded_maes(record, which="computed") -> dict:
    """{feature: value} of the `computed` or `beating` list of an Assessment's field, or {} when the field is absent."""
    field = record.get(FIELD)
    if field is None:
        return {}
    if which == "computed":
        return {entry["feature"]: entry["metric"]["value"] for entry in field["computed"]}
    return {entry["feature"]: entry["value"] for entry in field["beating"]}


def generated_examples(tmp_path, values: list, *, first: str, partitions: dict, configurations: dict, period_k=7, name="generated") -> Path:
    """An examples directory that holds one Workload, `gen_day`, around a daily series: `values` from the date `first` on.

    Its columns are `day`, `dow` (the weekday, 0 to 6) and `visits`, the target: no column of the Bike Workload, so a test on it
    shows that the Track reads only what the declaration names. Its lock and data checks are written for the series, so it verifies.
    """
    root = Path(tmp_path) / name
    workload = root / GENERATED
    (workload / "data").mkdir(parents=True)
    (workload / "licenses").mkdir()
    start = datetime.date.fromisoformat(first)
    days = [start + datetime.timedelta(days=i) for i in range(len(values))]
    data = workload / "data" / "series.csv"
    with data.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerow(["day", "dow", "visits"])
        for day, value in zip(days, values):
            writer.writerow([day.isoformat(), day.weekday(), int(value)])
    notice = workload / "licenses" / "notice.md"
    notice.write_text("A series generated by the test suite.\n", encoding="utf-8")
    (workload / "data-checks.json").write_text(json.dumps({
        "schema_version": "data-checks/1", "dataset_id": "generated-v1", "kind": "daily_series",
        "columns": ["day", "dow", "visits"], "total_column": "visits", "part_columns": ["visits"],
    }), encoding="utf-8")
    (workload / "data-sources.lock.json").write_text(json.dumps({
        "schema_version": "data-sources/1", "verified_on": "2026-11-22",
        "sources": [{
            "dataset_id": "generated-v1", "landing_url": "https://example.invalid/generated", "download_url": "https://example.invalid/generated.csv",
            "local_path": "data/series.csv", "sha256": hashlib.sha256(data.read_bytes()).hexdigest(), "size_bytes": data.stat().st_size,
            "rows": len(values), "license": "CC0-1.0", "notice": "licenses/notice.md", "native_key": "day",
            "date_min": days[0].isoformat(), "date_max": days[-1].isoformat(),
        }],
    }), encoding="utf-8")
    (workload / "workload.json").write_text(json.dumps({
        "schema_version": "workload/1", "track": "temporal_regression", "data_file": "data/series.csv",
        "licence_notice": "licenses/notice.md",
        "question": "How many visits on day t, knowing the visits up to day t - 1?",
        "objective": "A generated series for the single-feature tests.",
        "limitations": ["A generated series."],
        "id_prefix": "gen-day", "date_column": "day", "target_column": "visits", "target_unit": "visits per day",
        "period_k": period_k, "forbidden_features": ["visits"], "allowed_target_features": GENERATED_FEATURES,
        "partitions": partitions, "configurations": configurations,
    }, indent=2), encoding="utf-8")
    return root


def ridge(lag_features, *, alpha=1.0, calendar=("dow",)) -> dict:
    """A `ridge_pipeline` Configuration of the generated Workload over the given lag features and calendar columns."""
    names = [f["name"] for f in lag_features]
    return {
        "kind": "ridge_pipeline", "lag_features": list(lag_features), "calendar_columns": list(calendar),
        "encoder": {"columns": list(calendar), "handle_unknown": "ignore", "sparse_output": False},
        "scaler": {"columns": names},
        "ridge": {"alpha": alpha, "fit_intercept": True, "solver": "svd"},
        "post_processing": {"clip_min": 0},
    }


def init_generated(examples, study):
    code, payload, err = run_json("init", "--workload", GENERATED, "--study", study, "--examples-dir", examples)
    assert code == 0, (payload, err)
    return Path(study)


BLOCKER = '''
import importlib.abc, json, sys

BLOCKED = set(json.loads(sys.argv[1]))

class Blocker(importlib.abc.MetaPathFinder):
    def find_spec(self, name, path, target=None):
        if name.split(".")[0] in BLOCKED:
            raise ImportError(f"{name} is blocked in this environment")

sys.meta_path.insert(0, Blocker())
for name in sorted(BLOCKED):
    try:
        __import__(name)
    except ImportError:
        pass
    else:
        raise SystemExit(f"{name} is importable: the blocker does not work")
'''


def run_blocked(blocked, body: str, *args):
    """Run `body` in a fresh interpreter where the modules `blocked` cannot be imported; its last stderr line is JSON.

    `body` reads its own arguments from `sys.argv[2:]` and writes one JSON object to stderr last; the result is that object,
    with `loaded`, the blocked modules found in `sys.modules` at the end, added to it.
    """
    import subprocess
    import sys
    import textwrap

    script = BLOCKER + textwrap.dedent(body) + (
        "\nsys.stderr.write('\\n' + json.dumps({**RESULT, 'loaded': sorted(m for m in sys.modules if m.split('.')[0] in BLOCKED)}))\n"
    )
    done = subprocess.run([sys.executable, "-c", script, json.dumps(sorted(blocked)), *map(str, args)], capture_output=True, text=True)
    assert done.returncode == 0, done.stderr
    return json.loads(done.stderr.splitlines()[-1])
